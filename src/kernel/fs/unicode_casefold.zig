pub fn foldCodepoint(codepoint: u21, out: *[3]u21) u2 {
    if (codepoint < 0x80) {
        out[0] = if (codepoint >= 'A' and codepoint <= 'Z') codepoint + 32 else codepoint;
        return 1;
    }

    for (case_fold_expansions) |entry| {
        if (entry.codepoint == codepoint) {
            out.* = entry.values;
            return entry.len;
        }
        if (entry.codepoint > codepoint) break;
    }

    for (case_fold_ranges) |entry| {
        if (codepoint < entry.start) break;
        if (codepoint <= entry.end and ((codepoint - entry.start) % entry.step) == 0) {
            out[0] = @intCast(@as(i32, @intCast(codepoint)) + entry.delta);
            return 1;
        }
    }

    out[0] = codepoint;
    return 1;
}
